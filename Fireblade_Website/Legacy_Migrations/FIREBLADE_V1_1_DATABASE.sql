begin;

create table if not exists public.fireblade_employees (
  employee_id text primary key,
  employee_name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fireblade_devices (
  device_id text primary key,
  company_phone_number text not null,
  device_name text null,
  phone_label text null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fireblade_device_assignments (
  id bigint generated by default as identity primary key,
  device_id text not null references public.fireblade_devices(device_id) on update cascade,
  employee_id text not null references public.fireblade_employees(employee_id) on update cascade,
  assigned_from timestamptz not null default now(),
  assigned_until timestamptz null,
  created_at timestamptz not null default now(),
  constraint fireblade_assignment_dates_chk check (assigned_until is null or assigned_until >= assigned_from)
);

create index if not exists fireblade_assignment_device_dates_idx
  on public.fireblade_device_assignments(device_id, assigned_from desc);

create index if not exists fireblade_assignment_employee_dates_idx
  on public.fireblade_device_assignments(employee_id, assigned_from desc);

create unique index if not exists fireblade_one_active_assignment_per_device
  on public.fireblade_device_assignments(device_id)
  where assigned_until is null;

-- Keep direct browser/anon access blocked. Fireblade uses the backend secret
-- server-side, so these tables remain usable by the application with RLS on.
alter table public.fireblade_employees enable row level security;
alter table public.fireblade_devices enable row level security;
alter table public.fireblade_device_assignments enable row level security;

alter table public.fireblade_call_enquiries
  add column if not exists updated_by text null;

-- IMPORTANT: Keep every V1.0.1 view column in exactly the same position/name.
-- PostgreSQL permits CREATE OR REPLACE VIEW to append new columns, but it does
-- not permit inserting/reordering/removing existing columns. V1.1 fields are
-- therefore appended at the end. No raw/business data is dropped.
create or replace view public.fireblade_incoming_calls with (security_invoker = true) as
select
  -- Existing V1.0.1 columns: DO NOT reorder.
  pc.id as call_id,
  pc.device_id,
  pc.employee_name as collector_employee,
  pc.phone_number_raw,
  pc.phone_number_normalized,
  pc.contact_name as phone_contact_name,
  pc.direction,
  pc.started_at_epoch_ms,
  to_timestamp(pc.started_at_epoch_ms / 1000.0) as started_at,
  pc.duration_seconds,
  pc.received_at,
  enq.id as enquiry_id,
  enq.status as enquiry_status,
  enq.product_name,
  enq.requirement_details,
  enq.notes,
  enq.entered_by,
  enq.created_at as enquiry_created_at,
  enq.updated_at as enquiry_updated_at,
  con.id as contact_id,
  con.person_name,
  con.company_name,
  (
    select count(*)::integer
    from public.fireblade_contacts c2
    where c2.phone_number_normalized = pc.phone_number_normalized
  ) as known_contact_count,

  -- New V1.1 columns: append only.
  a.employee_id as registered_employee_id,
  emp.employee_name as registered_employee_name,
  coalesce(emp.employee_name, nullif(pc.employee_name, '')) as received_by,
  dev.company_phone_number,
  dev.device_name,
  dev.phone_label,
  enq.updated_by

from public.phase0_calls pc

left join lateral (
  select fa.*
  from public.fireblade_device_assignments fa
  where fa.device_id = pc.device_id
    and to_timestamp(pc.started_at_epoch_ms / 1000.0) >= fa.assigned_from
    and (
      fa.assigned_until is null
      or to_timestamp(pc.started_at_epoch_ms / 1000.0) < fa.assigned_until
    )
  order by fa.assigned_from desc
  limit 1
) a on true

left join public.fireblade_employees emp
  on emp.employee_id = a.employee_id

left join public.fireblade_devices dev
  on dev.device_id = pc.device_id

left join public.fireblade_call_enquiries enq
  on enq.call_id = pc.id

left join public.fireblade_contacts con
  on con.id = enq.contact_id

where pc.direction in ('INCOMING_ANSWERED', 'INCOMING_MISSED');

commit;
