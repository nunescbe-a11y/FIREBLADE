select count(*) as active_employees from public.fireblade_employees where active = true;
select count(*) as active_devices from public.fireblade_devices where active = true;
select count(*) as active_sim_lines from public.fireblade_device_lines where active = true;
select c.relname as view_name, coalesce(array_to_string(c.reloptions, ','), '') as view_options
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname='public' and c.relname='fireblade_incoming_calls';
