begin;

-- =============================================================
-- FIREBLADE V1.2 DATABASE UPGRADE
-- Safe for existing Fireblade / Phase-0 data.
-- Adds multi-SIM device lines, call SIM metadata columns,
-- repairs first-assignment backfill dates, and rebuilds the
-- incoming-calls view. Existing raw calls/enquiries are not deleted.
-- =============================================================

-- 1) Keep existing registries and make the legacy primary-number column
-- nullable for forward compatibility. V1.2 stores one/two numbers in
-- fireblade_device_lines; fireblade_devices.company_phone_number remains
-- a backwards-compatible SIM-1 mirror.
create table if not exists public.fireblade_employees (
  employee_id text primary key,
  employee_name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.fireblade_devices (
  device_id text primary key,
  company_phone_number text null,
  device_name text null,
  phone_label text null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.fireblade_devices
  alter column company_phone_number drop not null;

create table if not exists public.fireblade_device_assignments (
  id bigint generated by default as identity primary key,
  device_id text not null references public.fireblade_devices(device_id) on update cascade,
  employee_id text not null references public.fireblade_employees(employee_id) on update cascade,
  assigned_from timestamptz not null default now(),
  assigned_until timestamptz null,
  created_at timestamptz not null default now(),
  constraint fireblade_assignment_dates_chk check (assigned_until is null or assigned_until >= assigned_from)
);

create index if not exists fireblade_assignment_device_dates_idx
  on public.fireblade_device_assignments(device_id, assigned_from desc);
create index if not exists fireblade_assignment_employee_dates_idx
  on public.fireblade_device_assignments(employee_id, assigned_from desc);
create unique index if not exists fireblade_one_active_assignment_per_device
  on public.fireblade_device_assignments(device_id)
  where assigned_until is null;

-- Compatibility with early V1.1 attempts that temporarily stored phone/device
-- metadata directly on the assignment table with NOT NULL constraints.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='fireblade_device_assignments' and column_name='company_phone_number') then
    execute $q$update public.fireblade_device_assignments a set company_phone_number=d.company_phone_number from public.fireblade_devices d where a.device_id=d.device_id and a.company_phone_number is null$q$;
    execute 'alter table public.fireblade_device_assignments alter column company_phone_number drop not null';
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='fireblade_device_assignments' and column_name='device_name') then
    execute 'alter table public.fireblade_device_assignments alter column device_name drop not null';
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='fireblade_device_assignments' and column_name='phone_label') then
    execute 'alter table public.fireblade_device_assignments alter column phone_label drop not null';
  end if;
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='fireblade_device_assignments' and column_name='status') then
    execute 'alter table public.fireblade_device_assignments alter column status drop not null';
  end if;
end $$;

-- 2) One device may have SIM 1 and SIM 2. A unique slot lets the admin update
-- a number without creating another physical device.
create table if not exists public.fireblade_device_lines (
  id bigint generated by default as identity primary key,
  device_id text not null references public.fireblade_devices(device_id) on update cascade on delete cascade,
  sim_slot_index integer null check (sim_slot_index is null or sim_slot_index in (0,1)),
  phone_number text not null,
  line_label text null,
  carrier_name text null,
  subscription_id integer null,
  phone_account_id text null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fireblade_device_line_slot_uniq unique(device_id, sim_slot_index)
);

create index if not exists fireblade_device_lines_phone_idx
  on public.fireblade_device_lines(phone_number);
create index if not exists fireblade_device_lines_device_idx
  on public.fireblade_device_lines(device_id, active);

-- Migrate the old single phone number into SIM 1, without overwriting any
-- line already registered in V1.2.
insert into public.fireblade_device_lines (
  device_id, sim_slot_index, phone_number, line_label, active
)
select d.device_id, 0, d.company_phone_number, 'SIM 1', true
from public.fireblade_devices d
where nullif(trim(d.company_phone_number), '') is not null
on conflict (device_id, sim_slot_index) do nothing;

-- 3) Raw call metadata needed to distinguish SIM 1 vs SIM 2 when Android
-- exposes the phone account. Existing rows remain valid with NULL values.
alter table public.phase0_calls add column if not exists phone_account_id text null;
alter table public.phase0_calls add column if not exists phone_account_component text null;
alter table public.phase0_calls add column if not exists subscription_id integer null;
alter table public.phase0_calls add column if not exists sim_slot_index integer null;

alter table public.fireblade_call_enquiries
  add column if not exists updated_by text null;

-- 4) Repair a common rollout case: a phone was registered after its August
-- backfill was already uploaded. Only devices with exactly ONE assignment are
-- backdated, so historical ownership is never rewritten on reassigned phones.
with one_assignment_device as (
  select device_id
  from public.fireblade_device_assignments
  group by device_id
  having count(*) = 1
), first_eligible_call as (
  select pc.device_id,
         min(to_timestamp(pc.started_at_epoch_ms / 1000.0)) as first_call_at
  from public.phase0_calls pc
  where pc.started_at_epoch_ms >= (extract(epoch from timestamptz '2026-08-01 00:00:00+05:30') * 1000)::bigint
  group by pc.device_id
)
update public.fireblade_device_assignments a
set assigned_from = greatest(f.first_call_at, timestamptz '2026-08-01 00:00:00+05:30')
from one_assignment_device o
join first_eligible_call f on f.device_id = o.device_id
where a.device_id = o.device_id
  and f.first_call_at < a.assigned_from;

-- 5) If a collector is already sending a known employee name but a device has
-- no active assignment, automatically attach it only when that employee name
-- uniquely matches one registered employee. This repairs rollout gaps such as
-- a working phone that was uploaded before its admin assignment was saved.
with latest_name as (
  select distinct on (pc.device_id)
         pc.device_id,
         nullif(trim(pc.employee_name), '') as employee_name
  from public.phase0_calls pc
  where pc.started_at_epoch_ms >= (extract(epoch from timestamptz '2026-08-01 00:00:00+05:30') * 1000)::bigint
  order by pc.device_id, pc.started_at_epoch_ms desc
), unique_employee as (
  select l.device_id, min(e.employee_id) as employee_id
  from latest_name l
  join public.fireblade_employees e
    on lower(trim(e.employee_name)) = lower(trim(l.employee_name))
   and e.active = true
  where l.employee_name is not null
  group by l.device_id
  having count(*) = 1
), earliest as (
  select pc.device_id,
         greatest(min(to_timestamp(pc.started_at_epoch_ms / 1000.0)), timestamptz '2026-08-01 00:00:00+05:30') as assigned_from
  from public.phase0_calls pc
  where pc.started_at_epoch_ms >= (extract(epoch from timestamptz '2026-08-01 00:00:00+05:30') * 1000)::bigint
  group by pc.device_id
)
insert into public.fireblade_device_assignments(device_id, employee_id, assigned_from, assigned_until)
select u.device_id, u.employee_id, e.assigned_from, null
from unique_employee u
join earliest e on e.device_id = u.device_id
join public.fireblade_devices d on d.device_id = u.device_id
where not exists (
  select 1 from public.fireblade_device_assignments a
  where a.device_id = u.device_id and a.assigned_until is null
)
on conflict do nothing;

-- 6) Security: server-side Fireblade uses service_role. No anon/browser policy
-- is needed on these admin registries.
alter table public.fireblade_employees enable row level security;
alter table public.fireblade_devices enable row level security;
alter table public.fireblade_device_assignments enable row level security;
alter table public.fireblade_device_lines enable row level security;
alter table if exists public.fireblade_enquiry_audit enable row level security;

-- 7) Rebuild only the derived view. Raw data tables are untouched.
drop view if exists public.fireblade_incoming_calls;

create view public.fireblade_incoming_calls
with (security_invoker = true) as
select
  pc.id as call_id,
  pc.device_id,
  pc.employee_name as collector_employee,
  pc.phone_number_raw,
  pc.phone_number_normalized,
  pc.contact_name as phone_contact_name,
  pc.direction,
  pc.started_at_epoch_ms,
  to_timestamp(pc.started_at_epoch_ms / 1000.0) as started_at,
  pc.duration_seconds,
  pc.received_at,

  pc.phone_account_id as call_phone_account_id,
  pc.phone_account_component as call_phone_account_component,
  pc.subscription_id as call_subscription_id,
  pc.sim_slot_index as call_sim_slot_index,

  enq.id as enquiry_id,
  enq.status as enquiry_status,
  enq.product_name,
  enq.requirement_details,
  enq.notes,
  enq.entered_by,
  enq.created_at as enquiry_created_at,
  enq.updated_at as enquiry_updated_at,

  con.id as contact_id,
  con.person_name,
  con.company_name,
  (
    select count(*)::integer
    from public.fireblade_contacts c2
    where c2.phone_number_normalized = pc.phone_number_normalized
  ) as known_contact_count,

  a.employee_id as registered_employee_id,
  emp.employee_name as registered_employee_name,
  coalesce(emp.employee_name, nullif(pc.employee_name, '')) as received_by,

  -- Exact line when Android supplied a matching SIM/account. If the device has
  -- only one active line, use it as a safe fallback. For a dual-SIM call with
  -- no routing metadata, company_phone_number stays NULL rather than guessing.
  line_match.phone_number as company_phone_number,
  dev.device_name,
  dev.phone_label,
  line_match.id as resolved_line_id,
  line_match.line_label as resolved_line_label,
  line_match.carrier_name as resolved_line_carrier,
  line_match.sim_slot_index as resolved_sim_slot_index,
  case
    when line_match.id is null and line_count.active_line_count > 1 then 'MULTI_SIM_UNKNOWN'
    when line_match.id is null then 'NO_LINE'
    when pc.sim_slot_index is not null and line_match.sim_slot_index = pc.sim_slot_index then 'EXACT_SIM'
    when pc.subscription_id is not null and line_match.subscription_id = pc.subscription_id then 'EXACT_SIM'
    when nullif(pc.phone_account_id, '') is not null and line_match.phone_account_id = pc.phone_account_id then 'EXACT_SIM'
    when line_count.active_line_count = 1 then 'SINGLE_LINE_FALLBACK'
    else 'EXACT_SIM'
  end as line_resolution,
  enq.updated_by

from public.phase0_calls pc

left join lateral (
  select fa.*
  from public.fireblade_device_assignments fa
  where fa.device_id = pc.device_id
    and to_timestamp(pc.started_at_epoch_ms / 1000.0) >= fa.assigned_from
    and (fa.assigned_until is null or to_timestamp(pc.started_at_epoch_ms / 1000.0) < fa.assigned_until)
  order by fa.assigned_from desc
  limit 1
) a on true

left join public.fireblade_employees emp on emp.employee_id = a.employee_id
left join public.fireblade_devices dev on dev.device_id = pc.device_id

left join lateral (
  select count(*)::integer as active_line_count
  from public.fireblade_device_lines dlc
  where dlc.device_id = pc.device_id and dlc.active = true
) line_count on true

left join lateral (
  select dl.*
  from public.fireblade_device_lines dl
  where dl.device_id = pc.device_id
    and dl.active = true
    and (
      (pc.sim_slot_index is not null and dl.sim_slot_index = pc.sim_slot_index)
      or (pc.subscription_id is not null and dl.subscription_id = pc.subscription_id)
      or (nullif(pc.phone_account_id, '') is not null and dl.phone_account_id = pc.phone_account_id)
      or line_count.active_line_count = 1
    )
  order by
    case
      when pc.sim_slot_index is not null and dl.sim_slot_index = pc.sim_slot_index then 1
      when pc.subscription_id is not null and dl.subscription_id = pc.subscription_id then 2
      when nullif(pc.phone_account_id, '') is not null and dl.phone_account_id = pc.phone_account_id then 3
      else 4
    end,
    dl.sim_slot_index nulls last
  limit 1
) line_match on true

left join public.fireblade_call_enquiries enq on enq.call_id = pc.id
left join public.fireblade_contacts con on con.id = enq.contact_id
where pc.direction in ('INCOMING_ANSWERED', 'INCOMING_MISSED');

-- 8) Server-side privileges.
grant select, insert, update, delete on public.fireblade_employees to service_role;
grant select, insert, update, delete on public.fireblade_devices to service_role;
grant select, insert, update, delete on public.fireblade_device_assignments to service_role;
grant select, insert, update, delete on public.fireblade_device_lines to service_role;
grant select on public.fireblade_incoming_calls to service_role;

do $$
declare seq_name text;
begin
  seq_name := pg_get_serial_sequence('public.fireblade_device_assignments', 'id');
  if seq_name is not null then execute 'grant usage, select on sequence ' || seq_name || ' to service_role'; end if;
  seq_name := pg_get_serial_sequence('public.fireblade_device_lines', 'id');
  if seq_name is not null then execute 'grant usage, select on sequence ' || seq_name || ' to service_role'; end if;
end
$$;

commit;

-- Verification: read-only.
