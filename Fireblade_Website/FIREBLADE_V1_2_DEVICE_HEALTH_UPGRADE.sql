-- FIREBLADE V1.2 DEVICE HEALTH UPGRADE
-- Run this AFTER the V1.2 Dual-SIM migration has completed successfully.
-- This migration does not alter call records, enquiry data, employee/device IDs,
-- or historical device assignments.

begin;

create table if not exists public.fireblade_device_health (
  device_id text primary key,
  employee_name text,
  heartbeat_at timestamptz not null default now(),
  event_type text not null default 'HEARTBEAT',
  mobile_data_state text not null default 'UNKNOWN'
    check (mobile_data_state in ('ON','OFF','UNKNOWN')),
  internet_available boolean,
  network_type text,
  wifi_connected boolean,
  cellular_connected boolean,
  battery_percent integer check (battery_percent is null or (battery_percent between 0 and 100)),
  charging boolean,
  airplane_mode boolean,
  sim_count integer,
  sim1_state text,
  sim2_state text,
  default_data_sim_slot integer,
  apk_version text,
  android_version text,
  device_model text,
  pending_uploads integer,
  last_call_sync_epoch_ms bigint,
  boot_epoch_ms bigint,
  collector_state text,
  collector_message text,
  shutdown_confirmed_at timestamptz,
  updated_at timestamptz not null default now()
);

create index if not exists fireblade_device_health_heartbeat_idx
  on public.fireblade_device_health (heartbeat_at desc);

create table if not exists public.fireblade_device_health_history (
  id bigint generated by default as identity primary key,
  device_id text not null,
  observed_at timestamptz not null default now(),
  event_type text not null,
  mobile_data_state text,
  internet_available boolean,
  network_type text,
  wifi_connected boolean,
  cellular_connected boolean,
  battery_percent integer,
  charging boolean,
  airplane_mode boolean,
  sim_count integer,
  sim1_state text,
  sim2_state text,
  default_data_sim_slot integer,
  apk_version text,
  android_version text,
  device_model text,
  pending_uploads integer,
  collector_state text,
  note text
);

create index if not exists fireblade_device_health_history_device_time_idx
  on public.fireblade_device_health_history (device_id, observed_at desc);

alter table public.fireblade_device_health enable row level security;
alter table public.fireblade_device_health_history enable row level security;

comment on table public.fireblade_device_health is
  'Latest device-health heartbeat for each Fireblade MKT phone. Server/service key writes and reads this table.';
comment on table public.fireblade_device_health_history is
  'Event-oriented device-health history. Routine heartbeat rows are not inserted here to avoid unnecessary growth.';

commit;
